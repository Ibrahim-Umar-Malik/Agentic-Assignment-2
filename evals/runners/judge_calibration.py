"""R&D Question B (part 3): calibrate the LLM-as-judge against human labels.

    python -m evals.runners.judge_calibration build    # writes the 30-item set + a CSV for a human to fill
    python -m evals.runners.judge_calibration score    # judge scores; kappa once evals/datasets/judge_labels.csv is filled

Human labels cannot be generated by the system, so until the CSV has 30 human scores the result file says
"awaiting_human_labels" and reports only a clearly-labelled proxy: agreement with the GigSim client model.
"""

from __future__ import annotations

import asyncio
import csv
import json
import logging
import re
import sys

from pydantic import BaseModel, Field

from .common import (
    DATASETS,
    PERSONAS,
    ROOT,
    cohen_kappa,
    eval_env,
    load_dev,
    public_job,
    run_meta,
    split,
    write_result,
)

eval_env()
SET = DATASETS / "judge_set.jsonl"
LABELS = DATASETS / "judge_labels.csv"
GENERIC = re.compile(r"(?i)dear hiring manager|passionate|perfect fit|i am very interested|hi there|hello,")


class JudgeScore(BaseModel):
    relevance: int = Field(ge=1, le=5)
    evidence: int = Field(ge=1, le=5)
    clarity: int = Field(ge=1, le=5)
    opening: int = Field(ge=1, le=5)
    professionalism: int = Field(ge=1, le=5)
    overall: int = Field(ge=1, le=5)


def heuristic_judge(job: dict, letter: str) -> JudgeScore:
    low = letter.lower()
    skills = job.get("skills") or []
    cov = sum(s.lower() in low for s in skills) / len(skills) if skills else 0
    nums = len(re.findall(r"\d+(\.\d+)?\s?(%|x|ms|hours|k\b)", letter))
    words = len(letter.split())
    first = letter.strip().split(".")[0]
    rel = 1 + round(4 * cov)
    ev = min(5, 1 + 2 * nums + ("project" in low))
    cl = 5 if 60 <= words <= 220 else 3 if 40 <= words <= 300 else 2
    op = 2 if GENERIC.search(first) else 4 + (bool(re.search(r"\d", first)) or "?" in first)
    pro = 2 if GENERIC.search(letter) else 5
    overall = max(1, min(5, round((rel + 2 * ev + cl + op + pro) / 6)))
    return JudgeScore(relevance=rel, evidence=ev, clarity=cl, opening=min(5, op), professionalism=pro, overall=overall)


async def llm_judge(job: dict, letter: str) -> JudgeScore:
    from agent.nodes.common import load_prompt, wrap
    from core import llm

    if llm.is_offline("judge"):
        return heuristic_judge(job, letter)
    _, system = load_prompt("judge")
    out = await llm.call("judge", system, wrap("untrusted_job_post", f"{job['title']}\n{job['description']}") +
                         f"\n\nPROPOSAL:\n{letter}", JudgeScore)
    return out or heuristic_judge(job, letter)


async def build() -> None:
    from langgraph.checkpoint.memory import InMemorySaver
    from langgraph.store.memory import InMemoryStore

    from agent.graphs.bid_graph import build_bid_graph
    from core.db import init_db
    from gigsim_standin.app import sim
    from mcp_servers.marketplace import server
    from tests.fakes import gigsim_adapter

    from .gigsim_outcomes import GENERIC as TEMPLATE
    from .gigsim_outcomes import best_past

    init_db()
    graph = build_bid_graph().compile(checkpointer=InMemorySaver(), store=InMemoryStore())
    items = []
    for persona in PERSONAS:
        sim.reset()
        server._port_override = gigsim_adapter(f"dev-{persona}")
        rows = [r for r in split(load_dev(persona), "test") if r["_gold"]["kind"] in ("fit", "lowball")]
        n_agent = 0
        for i, row in enumerate(rows[:12]):
            sim.jobs[row["id"]] = row
            job = public_job(row)
            if i % 3 == 0:
                letter, source = TEMPLATE.format(skills=", ".join(job.get("skills") or [])), "template"
            elif i % 3 == 1 and n_agent >= 3:
                letter, source = best_past(persona), "reuse_past"
            else:
                tid = f"judge:{row['id']}"
                out = await graph.ainvoke({"user_id": "judge", "persona": persona, "thread_id": tid, "trace_id": tid, "job": job,
                                           "meta": {"hourly_floor": 40, "portfolio_id": persona}}, {"configurable": {"thread_id": tid}})
                if not out.get("draft"):
                    continue
                letter, source = out["draft"]["cover_letter"], "gigbid"
                n_agent += 1
            items.append({"id": f"J{len(items) + 1:02d}", "persona": persona, "job": job, "letter": letter, "source": source,
                          "gigsim_score": sim.decide(row, sim.clients[row["client_id"]], letter, float(row["budget"]), None, "j")["score"]})
    items = items[:30]
    SET.write_text("\n".join(json.dumps(x) for x in items) + "\n")
    with LABELS.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["id", "job_title", "job_description", "proposal", "human_overall_1to5", "notes"])
        for x in items:  # source hidden from the labeller on purpose (blind labelling)
            w.writerow([x["id"], x["job"]["title"], x["job"]["description"], x["letter"], "", ""])
    print(f"wrote {SET.relative_to(ROOT)} and {LABELS.relative_to(ROOT)} ({len(items)} items)")


def human_labels() -> dict[str, int]:
    if not LABELS.exists():
        return {}
    with LABELS.open() as f:
        return {r["id"]: int(r["human_overall_1to5"]) for r in csv.DictReader(f) if r.get("human_overall_1to5", "").strip().isdigit()}


def quadratic_kappa(a: list[int], b: list[int], k: int = 5) -> float | None:
    if not a:
        return None
    import itertools

    n = len(a)
    o = [[0.0] * k for _ in range(k)]
    for x, y in zip(a, b, strict=True):
        o[x - 1][y - 1] += 1
    ha = [a.count(i + 1) for i in range(k)]
    hb = [b.count(i + 1) for i in range(k)]
    num = den = 0.0
    for i, j in itertools.product(range(k), range(k)):
        w = (i - j) ** 2 / (k - 1) ** 2
        num += w * o[i][j]
        den += w * ha[i] * hb[j] / n
    return round(1 - num / den, 4) if den else 1.0


async def score() -> None:
    items = [json.loads(x) for x in SET.read_text().splitlines() if x.strip()]
    judged = []
    for x in items:
        s = await llm_judge(x["job"], x["letter"])
        judged.append({"id": x["id"], "source": x["source"], "judge": s.model_dump(), "gigsim_score": x["gigsim_score"]})
    human = human_labels()
    by_source = {}
    for src in sorted({j["source"] for j in judged}):
        g = [j["judge"]["overall"] for j in judged if j["source"] == src]
        by_source[src] = round(sum(g) / len(g), 2)
    # proxy only: GigSim client-model score binned to 1-5 (NOT a human label)
    def bin5(v: float) -> int:
        return 1 if v < 0 else 2 if v < 0.8 else 3 if v < 1.6 else 4 if v < 2.4 else 5

    proxy = [bin5(j["gigsim_score"]) for j in judged]
    jud = [j["judge"]["overall"] for j in judged]
    res = {"meta": run_meta(judge="heuristic rubric (offline)" if "offline" in str(run_meta().get("profile")) else "LLM judge"),
           "n_items": len(judged), "mean_overall_by_source": by_source,
           "proxy_vs_gigsim_client_model": {"note": "proxy only, not human agreement",
                                             "quadratic_weighted_kappa": quadratic_kappa(jud, proxy),
                                             "exact_agreement": round(sum(a == b for a, b in zip(jud, proxy, strict=True)) / len(jud), 3)},
           "items": judged}
    if len(human) >= 30:
        ids = [j["id"] for j in judged if j["id"] in human]
        h = [human[i] for i in ids]
        jj = [next(j["judge"]["overall"] for j in judged if j["id"] == i) for i in ids]
        res["human"] = {"status": "calibrated", "n": len(ids), "cohen_kappa": cohen_kappa(jj, h),
                        "quadratic_weighted_kappa": quadratic_kappa(jj, h),
                        "exact_agreement": round(sum(a == b for a, b in zip(jj, h, strict=True)) / len(h), 3)}
    else:
        res["human"] = {"status": "awaiting_human_labels", "labelled": len(human), "needed": 30,
                        "how": "fill human_overall_1to5 in evals/datasets/judge_labels.csv, then re-run `score`"}
    write_result("judge_calibration", res)
    print(json.dumps({k: v for k, v in res.items() if k != "items"}, indent=1))


if __name__ == "__main__":
    logging.disable(logging.INFO)
    cmd = sys.argv[1] if len(sys.argv) > 1 else "score"
    asyncio.run(build() if cmd == "build" else score())
